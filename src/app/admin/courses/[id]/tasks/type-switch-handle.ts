// Спільний контракт для форм полів завдання, які підтримують перенос
// сумісних даних при зміні типу (task-config-fields.tsx читає getValue()
// ПЕРЕД розмонтуванням старого підкомпонента, шукає трансформацію в
// type-compatibility.ts за парою (старий тип, новий тип), і якщо є —
// підставляє результат замість initialConfig новому підкомпоненту). Той
// самий принцип, що ImportableFieldsHandle (importable-fields.ts) — окремий
// тип, бо не всі задіяні компоненти мають імпорт лексики, і не всі
// компоненти з імпортом лексики задіяні тут.
export type TypeSwitchHandle<T> = {
  getValue: () => Partial<T>;
};
