// Безпечна студентська назва задачі з (можливо) сирого tasks.title — для
// будь-якого майбутнього заголовка/таба/пункту списку, що інакше показав
// би сирий title напряму. Правило "Робота над помилками" (мистейки-
// сторінки/error-review вже не читають сирий title взагалі — завжди назва
// типу, task-display-name.ts тут не викликається, бо в них немає "ручного
// title" гілки за задумом): якщо title виглядає автогенерованим (старий
// generateTaskTitle, task-title.ts, ДО виправлення "exercise names with a
// tail" — "<укр. назва типу>: <слова з конфігу>…" чи просто сама назва
// типу без хвоста), ігноруємо title і повертаємо французьку назву типу
// (getDefaultTaskName, default-task-labels.ts — ТА САМА мапа, що вже
// рендерить плашку типу над вправою, GlassBlock/getTaskBarText, і другий
// рядок рядків "Робота над помилками"). Якщо title НЕ автогенерований
// (вчителька переписала руками — "Cas particuliers", "HP", "1" тощо) —
// лишаємо його як є.
import { TASK_TYPE_LABELS } from "./task-type-meta";
import { getDefaultTaskName } from "./default-task-labels";

// Префікси старої автоназви — усі значення TASK_TYPE_LABELS
// (task-type-meta.ts, українські назви типів, якими generateTaskTitle
// будувала "<префікс>: ...") плюс варіант word_choice+cross_out
// ("Вибір зайвого", taskVariantLabel) — та сама мапа, що й сам генератор
// використовував, тож список префіксів лишається синхронним з генератором
// автоматично (нове значення в TASK_TYPE_LABELS одразу стає відомим
// префіксом тут).
const AUTO_TITLE_PREFIXES: readonly string[] = [...new Set([...Object.values(TASK_TYPE_LABELS), "Вибір зайвого"])];

// trimmed — уже обрізаний пробілами рядок (викликач нижче гарантує це).
export function isAutoGeneratedTaskTitle(trimmed: string): boolean {
  if (trimmed.length === 0) return false;
  // Старий generateTaskTitle повертав ГОЛУ назву типу, коли в config не
  // було прев'ю-елементів (fallback елементів.length === 0) — без
  // двокрапки взагалі.
  if (AUTO_TITLE_PREFIXES.includes(trimmed)) return true;
  // "<префікс>: <слова>" чи "<префікс>: <слова>…" (обрізано до ~60
  // символів) — основна форма автоназви.
  if (AUTO_TITLE_PREFIXES.some((prefix) => trimmed.startsWith(`${prefix}: `))) return true;
  // Запасна евристика — список префіксів може розійтися з генератором у
  // майбутньому (новий тип додано в один файл, забули інший): той самий
  // загальний силует "<щось>: <слова>…", що генератор завжди давав для
  // обрізаних прев'ю, упізнається навіть якщо префікс незнайомий.
  return /: .+…$/.test(trimmed);
}

// ordinal — порядковий номер серед кількох задач ОДНАКОВОЇ фінальної
// назви в тому самому списку (рахує й призначає викликач, напр. error-
// review-block.tsx чи мистейки-список — ця функція не бачить сусідніх
// задач); null/undefined/0 — назва унікальна в списку, без номера.
export function taskDisplayName(type: string, title: string | null | undefined, ordinal?: number | null): string {
  const trimmed = (title ?? "").trim();
  const base = trimmed && !isAutoGeneratedTaskTitle(trimmed) ? trimmed : getDefaultTaskName(type);
  return ordinal ? `${base} · ${ordinal}` : base;
}
