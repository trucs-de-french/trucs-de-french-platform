// Спільна нормалізація "слово -> те, що фізично влазить у клітинку сітки"
// для word_search/crossword — ОДНЕ місце, використовується генераторами
// розкладки (word-search-grid.ts/crossword-grid.ts), серверною перевіркою
// відповіді (grade.ts) і клієнтським швидким фідбеком під час гри
// (word-search.tsx). config.words[].word (легенда/підказки/показ
// "правильного слова") НІКОЛИ не проганяється через цю функцію — там
// лишається оригінал, як ввела вчителька чи як у словнику (напр.
// "grand-mère"). Лише розміщення в сітці й звірка з тим, що студент
// виділив/увів, працюють з очищеною формою (тут — "GRANDMERE"): дефіс/
// апостроф/пробіл фізично не можуть бути окремою клітинкою рядка.
export function sanitizeWordForGrid(word: string): string {
  return word.replace(/[^\p{L}]/gu, "");
}
