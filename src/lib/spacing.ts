// Централізована система вертикальних відступів студентських сторінок —
// той самий патерн, що button-styles.ts/input-styles.ts: рядок класів, не
// компонент, підставляється напряму в className=. Мета та сама — наступна
// правка одного відступу це правка в ОДНОМУ місці, а не в 10+ файлах.
//
// Узгоджена система (розвідка перед впровадженням, ця сесія):
//   H1 (заголовок сторінки) → наступний контент:        32px (mt-8)
//   H2 (підзаголовок) → текст під ним:                   16px (mt-4)
//   Абзац → абзац:                                        16px (space-y-4 / mb-4)
//   Текст → картинка/вправа/блок вправ (зміна формату):   32px (mt-8 / gap-8)
//   Внутрішній padding карток і блоків:            16px моб. / 24px десктоп (p-4 md:p-6)
//   Усередині блоку вправи (інструкція↔тіло↔кнопка↔край): 16px моб. / 24px десктоп (EXERCISE_STACK)
//   Повторювані елементи тіла вправи (твердження, слова):  16px (gap-4, EXERCISE_BODY_ITEMS_GAP)
//   Підпис → його контент усередині елемента тіла:          8px (gap-2, EXERCISE_LABEL_GAP)
//
// ВИНЯТОК за свідомим рішенням (ця сесія): H2 "Завдання"/"Вправи"/секція
// DELF → список вправ, і відступ МІЖ вправами в такому списку — 16px
// (H2_TO_CONTENT) і gap-4 (EXERCISE_LIST_GAP), НЕ 32px і не окрема
// "текст→блок" категорія — список вправ трактується як звичайний контент
// під підзаголовком, не як зміна формату.
//
// TEXT_TO_EXERCISES — те саме "текст→вправа" (32px), але окрема константа
// від H1_TO_CONTENT (хоч значення однакове): застосовується САМЕ до секції
// "Вправи" в тілі статті/сторінки, коли перед нею вже був текстовий
// контент (не h1) — щоб відступ там не плутався з винятком вище
// (H2 секції "Вправи" → сам список — це 16px, а секція ЦІЛОМ → те, що
// стояло ДО неї — 32px, зміна формату).
//
// .rich-text (globals.css) реалізує ту саму H1/H2/абзацну шкалу ЗВИЧАЙНИМ
// CSS, не цими Tailwind-константами (TipTap-контент рендериться через
// dangerouslySetInnerHTML, класи сюди не дотягнутись) — при зміні значень
// тут звірити з globals.css вручну, вони не пов'язані технічно.
export const H1_TO_CONTENT = "mt-8";
export const H2_TO_CONTENT = "mt-4";
export const EXERCISE_LIST_GAP = "gap-4";
export const TEXT_TO_EXERCISES = "mt-8";

// Єдиний вертикальний ритм УСЕРЕДИНІ блоку вправи (EXERCISE_BLOCK_CLASS):
// відступ від краю блоку до першого елемента, між інструкцією і тілом, між
// тілом і рядком кнопки/результату, між рядком і краєм блоку — усюди
// ОДНАКОВИЙ і дорівнює padding самого блоку (EXERCISE_BLOCK_CLASS: p-4
// md:p-6) — значення тут МУСЯТЬ збігатися з тими p-4/md:p-6, інакше
// зовнішній (padding) і внутрішній (між частинами) ритм розійдуться.
// Ставиться на КОРІНЬ кожного студентського компонента вправи; прямі діти —
// лише "великі" частини (інструкція, медіа, тіло, рядок кнопки/результату,
// блок правильних відповідей), кожна БЕЗ власного зовнішнього margin.
export const EXERCISE_STACK = "flex flex-col gap-4 md:gap-6";

// Між ПОВТОРЮВАНИМИ елементами всередині тіла вправи (твердження true_false,
// слова letter_gaps/letter_rearrangement, речення word_choice, пари
// "підказка + плитки") — один рівень вкладеності нижче за EXERCISE_STACK,
// свідомо без md:-варіанту (це вже дрібніший, внутрішній ритм, не потребує
// окремого збільшення на десктопі). НЕ стосується "карткових" сіток
// (легенда філворду/кросворду, банки плиток drag_drop/sort_columns,
// картки-зображення image_match/chronological_order) — там свій, менший,
// спеціально підібраний gap, не чіпається цією константою.
export const EXERCISE_BODY_ITEMS_GAP = "gap-4";

// Між підписом (напр. "Визначення: ...") і його контентом (плитки літер,
// картки) всередині ОДНОГО елемента тіла — найдрібніший рівень ритму.
export const EXERCISE_LABEL_GAP = "gap-2";
