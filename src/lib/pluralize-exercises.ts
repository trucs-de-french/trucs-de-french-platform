// Українська плюралізація "вправу/вправи/вправ" (знахідний відмінок) —
// стандартне mod10/mod100 правило, той самий принцип, що pluralizePoints.
// Раніше жила лише як локальна функція на сторінці сцени (текст
// підтвердження видалення content-блоку з прикріпленими вправами); тепер
// спільна — та сама форма потрібна й на кнопці "Створити N вправ" (bulk-
// from-vocab).
export function pluralizeExercisesAccusative(n: number): "вправу" | "вправи" | "вправ" {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return "вправу";
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "вправи";
  return "вправ";
}
