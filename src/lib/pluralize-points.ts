// Українська плюралізація "бал/бали/балів" — стандартне правило (1 бал,
// 2-4 бали крім 12-14, решта — балів). Рішення приймається з округленого
// до найближчих 0.5 значення (те саме округлення, що formatScore,
// format-points.ts) — не з сирого числа з хвостом float-арифметики: інакше
// "7.96" (округлюється до показу як "8") міг би дати "бала" замість
// коректного "8 балів". Половинне значення ("0,5", "1,5", "24,5") —
// завжди родовий однини "бала".
export function pluralizePoints(n: number): "бал" | "бали" | "балів" | "бала" {
  const rounded = Math.round(n * 2) / 2;
  const abs = Math.abs(rounded);
  if (!Number.isInteger(abs)) return "бала";
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return "бал";
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "бали";
  return "балів";
}
