// Нерозривні пробіли (U+00A0, не U+202F — гарантований гліф у Lora/Nunito)
// за правилами французької типографіки, застосовуються ЛИШЕ при показі
// (ніколи при збереженні), щоб "?", "!", ";", ":" і закриваюча "»" не
// переносились на новий рядок окремо від слова, а відкриваюча "«" — від
// першого слова цитати. Звичайні пробіли (U+0020) лише; вже наявні NBSP/
// narrow NBSP — інший код-пойнт, regex їх не торкається. Зовнішні пробіли
// рядка (trim) НЕ чіпаються — правила спрацьовують лише там, де пробіл
// безпосередньо прилягає до одного з цих знаків.
export function frenchNbsp(text: string | null | undefined): string {
  if (!text) return text ?? "";
  return text
    .replace(/ +([?!;:])/g, " $1")
    .replace(/«[ ]+/g, "« ")
    .replace(/[ ]+»/g, " »");
}

// Безпечна версія для HTML (інструкції/callout після sanitize): розбиває
// рядок на теги й текст між ними (split із групою в регулярці чергує
// текст/тег/текст/...), frenchNbsp застосовується ЛИШЕ до текстових
// частин (парні індекси) — вміст і атрибути тегів (непарні індекси)
// лишаються незмінними.
const HTML_TAG_RE = /(<[^>]+>)/g;

export function frenchNbspHtml(html: string | null | undefined): string {
  if (!html) return html ?? "";
  return html
    .split(HTML_TAG_RE)
    .map((part, i) => (i % 2 === 1 ? part : frenchNbsp(part)))
    .join("");
}
