// Консервативний fallback-зіставлювач для matchTranslatedFormInText
// (vocab-match.ts) — вчителька вписує СЛОВНИКОВУ форму слова
// (translatedForm/translatedForms), а в реченні воно часто стоїть в іншому
// відмінку/числі з типовим українським чергуванням основи (дозвіл/дозволу,
// стіл/стола, ніч/ночі, рік/року, кінь/коня, сон/сну, день/дня,
// рука/руці, друг/друзі). Точний підрядковий збіг (крок 1, vocab-match.ts)
// цього не ловить — рядки просто різні. Цей модуль — ЄДИНИЙ і ВУЗЬКИЙ
// запасний крок: закрита таблиця відмінкових закінчень + закрита таблиця
// чергувань (і<->о/е, випадний голосний, перша палаталізація к/г/х), без
// жодної "розмитої" відстані/евристики — хибний позитив (підсвічене
// випадкове слово) тут гірший за промах.

// 10 українських голосних — апостроф/м'який знак НЕ голосні.
const VOWELS = new Set(["а", "я", "у", "ю", "е", "є", "о", "и", "і", "ї"]);

// Лише Кирилиця (+апостроф/дефіс, як і узгоджена клітинка слова в
// vocab-match.ts) — фальбек НІКОЛИ не застосовується до французького
// тексту чи випадкових латинських вставок в УКР тексті.
const CYRILLIC_WORD_RE = /^[\p{Script=Cyrillic}'’ʼ-]+$/u;

// Закрита таблиця відмінкових/числових закінчень (до 4 літер) — рівно той
// список, що узгоджений із задачею; НЕ евристика "довільний суфікс", будь-
// який "хвіст" поза цим списком (напр. "иця", "це", "ина", "ка") одразу
// означає "не збіг", без жодних compromise.
const CASE_ENDINGS = [
  "",
  "а", "я", "у", "ю", "е", "є", "о", "и", "і", "ї",
  "ом", "ем", "єм", "ою", "ею", "єю",
  "ові", "еві", "єві", "ів", "їв",
  "ам", "ям", "ах", "ях", "ами", "ями",
  "ого", "ому", "ій", "ої", "ий",
];

// Підмножина закінчень, дозволена для форм-кандидатів на М'ЯКУ основу
// (словникова форма закінчується на "ь", напр. "кінь", "день") — М'ЯКІ
// закінчення лише. Без цього обмеження "кінь" зловив би "кіно" (закінчення
// "о" — тверде, у кандидата просто НЕМА give-away м'якого закінчення).
const SOFT_ENDINGS = new Set(["я", "ю", "є", "ї", "і", "ем", "єм", "ів", "їв", "ям", "ями", "ях", "ій"]);

// к/г/х -> ц/з/с — перша палаталізація (рука/руці, друг/друзі, нога/нозі,
// книга/книзі) — застосовується ТІЛЬКИ коли закінчення кандидата рівно "і"
// (рука/руках — закінчення "ах", без палаталізації — тут це правило НЕ
// спрацює, бо ending !== "і", і це правильно: "рукам"/"руках" не чергують
// останню согласну).
const CONSONANT_ALTERNATION: Record<string, string> = { к: "ц", г: "з", х: "с" };

// Основа словникової форми — відрізаємо "ь" (запам'ятовуємо "м'яка
// основа") АБО один кінцевий голосний (школа -> школ); якщо форма вже
// закінчується на согласну (стіл, ніч, рік, сон, друг) — основа = сама
// форма, без відрізання.
function stripFormStem(form: string): { stem: string; soft: boolean } {
  if (form.endsWith("ь")) return { stem: form.slice(0, -1), soft: true };
  const last = form[form.length - 1];
  if (VOWELS.has(last)) return { stem: form.slice(0, -1), soft: false };
  return { stem: form, soft: false };
}

// Усі варіанти основи словникової форми, дозволені чергуваннями —
// ЗАВЖДИ містить саму основу без змін (ідентичність, для звичайних
// словозмін без чергування: школа/школи, вікно/вікна, лев/лева) плюс (якщо
// застосовно) варіанти з і<->о/е на останньому голосному основи, варіант
// без випадного о/е/і між двома останніми согласними основи, і варіант з
// чергуванням останньої согласної к/г/х (лише коли ending — рівно "і").
// Жодні з цих чергувань НЕ комбінуються між собою (кожен — окрема
// кандидатна основа) — спеціально консервативно, щоб не плодити зайві
// варіанти, яких немає в задачі.
function stemVariants(stem: string, ending: string): string[] {
  const variants = new Set<string>([stem]);

  // і<->о, і<->е — лише на ОСТАННЬОМУ голосному основи (дозвіл/дозволу,
  // стіл/стола, ніч/ночі, рік/року, кінь (основа "кін")/коня).
  const lastI = stem.lastIndexOf("і");
  if (lastI !== -1) {
    variants.add(stem.slice(0, lastI) + "о" + stem.slice(lastI + 1));
    variants.add(stem.slice(0, lastI) + "е" + stem.slice(lastI + 1));
  }

  // Випадний голосний о/е/і МІЖ двома останніми согласними основи (сон
  // (о між "с" і "н")/сну, день-ь -> "ден" (е між "д" і "н")/дня) — рівно
  // останні три літери основи мають бути "согласна-голосна-согласна", де
  // голосна — одна з о/е/і; інакше варіант не додається.
  if (stem.length >= 3) {
    const a = stem[stem.length - 3];
    const v = stem[stem.length - 2];
    const b = stem[stem.length - 1];
    if ((v === "о" || v === "е" || v === "і") && !VOWELS.has(a) && !VOWELS.has(b)) {
      variants.add(stem.slice(0, stem.length - 3) + a + b);
    }
  }

  // Перша палаталізація — тільки коли саме "і" витягнуте з кандидата як
  // закінчення (рука/руці, друг/друзі, нога/нозі, книга/книзі).
  if (ending === "і") {
    const lastConsonant = stem[stem.length - 1];
    const mapped = CONSONANT_ALTERNATION[lastConsonant];
    if (mapped) variants.add(stem.slice(0, -1) + mapped);
  }

  return [...variants];
}

// Чи годиться ЦЯ форма (один рядок з getTranslatedForms) для fallback-
// зіставлення — лише одне кириличне слово (без пробілу, фрази лишаються
// виключно точним збігом, крок 1) довжиною від 3 літер після trim.
export function isFallbackEligibleForm(form: string): boolean {
  const trimmed = form.trim();
  return trimmed.length >= 3 && !/\s/.test(trimmed) && CYRILLIC_WORD_RE.test(trimmed);
}

// Головна перевірка: чи може словникова "form" (translatedForm/
// translatedForms, вже пройшла isFallbackEligibleForm) зійтись із
// реальним словом "candidate" з тексту через одне з дозволених чергувань.
// Порівняння регістронезалежне; апостроф/дефіс — рівно як написано (на
// відміну від normalizeWordForMatch в vocab-match.ts, тут варіанти
// апострофа НЕ зводяться одне до одного — українські слова з апострофом у
// відмінкових закінченнях не трапляються, спеціальна обробка лише
// додавала б складність без потреби).
export function matchesUkAlternation(form: string, candidate: string): boolean {
  const f = form.trim().toLowerCase();
  if (f.length < 3 || /\s/.test(f) || !CYRILLIC_WORD_RE.test(f)) return false;
  const c = candidate.toLowerCase();
  if (!CYRILLIC_WORD_RE.test(c)) return false;

  const { stem: formStem, soft } = stripFormStem(f);
  const allowedEndings = soft ? CASE_ENDINGS.filter((e) => SOFT_ENDINGS.has(e)) : CASE_ENDINGS;

  for (const ending of allowedEndings) {
    if (!c.endsWith(ending)) continue;
    const stemC = c.slice(0, c.length - ending.length);
    if (stemC.length === 0) continue;
    if (stemVariants(formStem, ending).includes(stemC)) return true;
  }
  return false;
}
