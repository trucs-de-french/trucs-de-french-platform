-- ============================================================================
-- Корекція структури DELF: кожен курс = набір повних тестів (CO+CE+PE+PO),
-- а не плаский пул задач. delf_mode виявився хибним припущенням — режим
-- (Entraînement/Examen blanc) обирається студентом під час проходження
-- ОДНОГО Й ТОГО Ж комплекту задач тесту, а не є властивістю задачі при
-- авторстві, тож ця колонка видаляється (нічого не задеплоєно в проді, дані
-- ще не встигли накопичитись).
-- ============================================================================

alter table public.tasks drop column if exists delf_mode;

-- Без жорсткого максимуму (напр. 30) — обсяг контенту це рішення про
-- контент, не про цілісність даних; лише позитивне ціле число.
alter table public.tasks add column delf_test_number integer
  constraint tasks_delf_test_number_check check (delf_test_number > 0);
