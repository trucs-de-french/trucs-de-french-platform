-- ============================================================================
-- Виправлення "Could not choose the best candidate function... between
-- copy_task(...5 args) і copy_task(...6 args)" — 0032 додала p_task_group_id
-- ШОСТИМ параметром через "create or replace function", очікуючи, що це
-- замінить 5-параметрову версію з 0025. У Postgres це не так: ідентичність
-- функції визначається СПИСКОМ ТИПІВ параметрів, тож інший список (навіть
-- лише з одним доданим default-параметром) створює ОКРЕМЕ перевантаження,
-- не заміщує старе. Відтоді в БД існують ДВІ функції одночасно:
--   copy_task(uuid, uuid, uuid, text, integer)                    -- 0025, незмінна відтоді
--   copy_task(uuid, uuid, uuid, text, integer, uuid default null) -- 0032, тіло оновлено в 0034
-- Виклик рівно 5 позиційних/іменованих аргументів (copyTask() у
-- src/app/admin/tasks/actions.ts) підходить під ОБИДВІ (6-параметрова
-- приймає його завдяки default для p_task_group_id) — звідси
-- неоднозначність. Виклик з p_task_group_id (copyTaskInGroup() у
-- src/app/admin/task-groups/actions.ts) неоднозначності не мав: іменований
-- аргумент p_task_group_id відсутній у 5-параметровій сигнатурі, тож вона
-- одразу відкидається як кандидат.
--
-- 6-параметрова версія (0034) при p_task_group_id = NULL поводиться як
-- строгий СУПЕРНАБІР 5-параметрової: ті самі поля/значення при INSERT
-- (scene_id/material_id/delf_section/delf_test_number не обнуляються, коли
-- task_group_id null — лише task_group_id додатково пишеться як null), а
-- order_index рахується ТОЧНІШЕ — і по delf_section/delf_test_number теж
-- (0034 сама була фіксом цього пропуску, але torkнулась лише 6-параметрової
-- сигнатури; забута 5-параметрова версія й далі несе стару вужчу логіку).
-- Тобто лишена 5-параметрова функція не просто зайва — вона й досі БАГАСТА
-- копія, якщо колись обереться. Видаляємо її повністю, лишаючи єдину,
-- актуальну 6-параметрову як джерело правди.
--
-- GRANT: у жодній міграції немає окремого "grant execute" на copy_task (як
-- і на будь-яку іншу функцію проєкту) — обидва перевантаження покладались
-- на дефолтний EXECUTE-грант Postgres для PUBLIC при створенні функції.
-- Додаткового GRANT на 6-параметрову версію не потрібно.
-- ============================================================================

drop function if exists public.copy_task(uuid, uuid, uuid, text, integer);

notify pgrst, 'reload schema';
